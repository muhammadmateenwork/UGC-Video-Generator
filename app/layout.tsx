import type { Metadata } from "next";
import { Fraunces, Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Editorial display serif for headlines — pairs with Geist Sans for body
// text so the site reads as an edited publication rather than a generic
// SaaS template, matching the ink/orange design direction's own intent.
const fraunces = Fraunces({
  variable: "--font-fraunces",
  subsets: ["latin"],
  axes: ["opsz", "SOFT", "WONK"],
});

export const metadata: Metadata = {
  title: "UGC Video Generator",
  description:
    "Send a product URL, get a short UGC-style marketing video back — background, trending audio, GIF, and caption, all picked and assembled automatically.",
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${fraunces.variable} h-full`}
    >
      <body className="h-full antialiased">{children}</body>
    </html>
  );
}
